// The pure parts of the release build: what each target is, the header rules with the Content-Security-Policy, the
// static redirects, robots.txt, the web app manifest, the merged sitemap and the service worker's settings. No file
// system here, so all of it is unit-tested (release/site.test.ts); release/assemble.ts writes the files.

export type TargetId = 'preview' | 'production';

export interface Target {
  id: TargetId;
  /** The origin the build answers on. */
  origin: string;
  /** The Worker that serves it (the "name" of its wrangler config). */
  worker: string;
  config: string;
  /** Search engines may index it (production only: the preview says noindex everywhere). */
  indexable: boolean;
}

