export interface SitemapEntry { loc: string; lastmod?: string }

/** Adds the old content pages to the app's sitemap (which already lists its own pages with their hreflang links). */
export function mergeSitemap(appSitemap: string, extra: readonly SitemapEntry[]): string {
  const close = appSitemap.lastIndexOf('</urlset>');
  if (close < 0) throw new Error('the app sitemap has no </urlset>');
  const present = new Set([...appSitemap.matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => m[1]));
  const add = extra.filter((e) => !present.has(e.loc)).map((e) => `  <url>\n    <loc>${e.loc}</loc>${e.lastmod ? `\n    <lastmod>${e.lastmod}</lastmod>` : ''}\n  </url>\n`);
  return appSitemap.slice(0, close) + add.join('') + appSitemap.slice(close);
}

/** What the generated pages of the app get in their head: the manifest, the home-screen icon and the worker loader. */
export const HEAD_TAGS = [
  '<link rel="manifest" href="/manifest.json">',
  '<link rel="apple-touch-icon" href="/apple-touch-icon.png">',
  '<script src="/sw-register.js" defer></script>',
] as const;

export function injectHead(html: string): string {
  const at = html.indexOf('</head>');
  if (at < 0) throw new Error('page without </head>');
  if (html.includes(HEAD_TAGS[2])) return html;
  return `${html.slice(0, at)}${HEAD_TAGS.join('\n')}\n${html.slice(at)}`;
}

export interface SwConfig {
  build: string;
  precache: string[];
  startPages: Record<string, string>;
  libPrefixes: string[];
  libCache: string;
  navTimeoutMs: number;
}

/** The service worker source: the template with this build's settings in place of its development defaults. */
export function serviceWorkerSource(template: string, cfg: SwConfig): string {
  const marker = /\/\*__CONFIG__\*\/ \{[^\n]*\};/;
  if (!marker.test(template)) throw new Error('sw.template.js has no /*__CONFIG__*/ line');
  return template.replace(marker, `${JSON.stringify(cfg)};`);
}

/** The files a new service worker stores at install: every hashed build file but source maps, and the start pages. */
export function precacheList(files: readonly string[], startPages: readonly string[]): string[] {
  const build = files.filter((f) => f.startsWith('/static/') && !f.endsWith('.map')).sort();
  return [...startPages, ...build];
}
