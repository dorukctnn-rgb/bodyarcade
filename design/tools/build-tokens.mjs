// Build design/tokens/tokens.css and tokens.json from tokens.mjs.
// node design/tools/build-tokens.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { palette, themes, hud, type, space, radius, motion, elevation } from '../tokens/tokens.mjs';
import { BREAKPOINTS, hudMetrics } from '../tokens/layout.mjs';

const dir = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(dir, '..', 'tokens');

const lines = [];
const add = (s = '') => lines.push(s);
const flat = (prefix, obj) => Object.entries(obj).flatMap(([k, v]) =>
  typeof v === 'object' ? flat(`${prefix}-${k}`, v) : [[`${prefix}-${k}`, v]]);

add('/* BodyArcade design tokens. Generated by design/tools/build-tokens.mjs from tokens.mjs. Do not edit by hand. */');
add('');
add('@font-face {');
add('  font-family: "Savate";');
add('  src: url("../fonts/savate-var.woff2") format("woff2");');
add('  font-weight: 500 900;');
add('  font-style: normal;');
add('  font-display: swap;');
add('}');
add('@font-face {');
add('  font-family: "National Park";');
add('  src: url("../fonts/national-park-var.woff2") format("woff2");');
add('  font-weight: 400 800;');
add('  font-style: normal;');
add('  font-display: swap;');
add('}');
add('');
add(':root {');
add('  color-scheme: light dark;');
add('  /* Raw palette */');
for (const [k, v] of flat('--ba', palette)) add(`  ${k}: ${v};`);
add('');
add('  /* Semantic colours, light theme (default) */');
for (const [k, v] of Object.entries(themes.light)) add(`  --ba-${k}: ${v};`);
add('');
add('  /* HUD plates: the same in both themes, they sit on a camera mirror or a game scene */');
for (const [k, v] of Object.entries(hud)) add(`  --ba-hud-${k}: ${v};`);
add('');
add('  /* Type */');
add(`  --ba-font-display: ${type.display};`);
add(`  --ba-font-text: ${type.text};`);
for (const [k, v] of Object.entries(type.size)) add(`  --ba-text-${k}: ${v};`);
for (const [k, v] of Object.entries(type.display)) add(`  --ba-display-${k}: ${v};`);
for (const [k, v] of Object.entries(type.weight)) add(`  --ba-weight-${k}: ${v};`);
for (const [k, v] of Object.entries(type.leading)) add(`  --ba-leading-${k}: ${v};`);
for (const [k, v] of Object.entries(type.tracking)) add(`  --ba-tracking-${k}: ${v};`);
add('');
add('  /* Space, radius, elevation, motion */');
for (const [k, v] of Object.entries(space)) add(`  --ba-space-${k}: ${v};`);
for (const [k, v] of Object.entries(radius)) add(`  --ba-radius-${k}: ${v};`);
for (const [k, v] of Object.entries(elevation)) add(`  --ba-elev-${k}: ${v};`);
for (const [k, v] of Object.entries(motion)) add(`  --ba-${k}: ${v};`);
add('');
add('  /* HUD layout (CSS version of design/tokens/layout.mjs; layout.mjs is the reference) */');
add('  --ba-hud-margin: clamp(12px, 3vmin, 40px);');
add('  --ba-hud-gap: clamp(8px, 1.5vmin, 20px);');
add('  --ba-hud-command-floor: 0px;');
add('  --ba-hud-command: max(8svh, var(--ba-hud-command-floor));');
add('  --ba-hud-numeral: clamp(28px, 4.2svh, 60px);');
add('  --ba-hud-label: clamp(13px, calc(0.4 * var(--ba-hud-numeral)), 22px);');
add('  --ba-hud-reason: clamp(18px, 3svh, 36px);');
add('  --ba-cam-aspect: 1.3333;');
add('  --ba-pip-h: min(clamp(72px, 24svh, 220px), calc(24vw / var(--ba-cam-aspect)));');
add('  --ba-pip-w: calc(var(--ba-pip-h) * var(--ba-cam-aspect));');
add('}');
add('');
add('/* Phones: the short side is under 500 px. The command gets a physical floor. */');
add('@media (max-width: 499px), (max-height: 499px) {');
add('  :root { --ba-hud-command-floor: 44px; }');
add('}');
add('@media (max-height: 499px) and (orientation: landscape) {');
add('  :root { --ba-hud-command-floor: 52px; }');
add('}');
add('@media (orientation: portrait) {');
add('  :root {');
add('    --ba-cam-aspect: 0.75;');
add('    --ba-pip-w: min(clamp(96px, 30vw, 240px), calc(22svh * var(--ba-cam-aspect)));');
add('    --ba-pip-h: calc(var(--ba-pip-w) / var(--ba-cam-aspect));');
add('  }');
add('}');
add('@media (min-width: 768px) { :root { font-size: 106.25%; } }');
add('');
add('/* Dark theme: follows the system unless the page pins a theme with data-theme. */');
add('@media (prefers-color-scheme: dark) {');
add('  :root:not([data-theme="light"]) {');
for (const [k, v] of Object.entries(themes.dark)) add(`    --ba-${k}: ${v};`);
add('  }');
add('}');
add(':root[data-theme="dark"] {');
for (const [k, v] of Object.entries(themes.dark)) add(`  --ba-${k}: ${v};`);
add('}');
add('');
add('/* Reduced motion: keep feedback, drop movement. */');
add('@media (prefers-reduced-motion: reduce) {');
add('  :root {');
add('    --ba-dur-press: 1ms;');
add('    --ba-dur-state: 1ms;');
add('    --ba-dur-enter: 1ms;');
add('    --ba-dur-celebrate: 1ms;');
add('  }');
add('}');
writeFileSync(path.join(out, 'tokens.css'), lines.join('\n') + '\n');

const table = BREAKPOINTS.map((b) => {
  const m = hudMetrics(b);
  return { id: b.id, w: b.w, h: b.h, class: m.cls, insets: m.insets, margin: m.margin, gap: m.gap, font: m.font, pip: m.pip, live: m.live };
});
writeFileSync(path.join(out, 'tokens.json'), JSON.stringify({
  $comment: 'Generated from design/tokens/tokens.mjs and layout.mjs. Game code reads colours and HUD sizes from here.',
  palette, themes, hud, type, space, radius, motion, elevation, hudBreakpoints: table,
}, null, 2) + '\n');
console.log('tokens.css and tokens.json written');
