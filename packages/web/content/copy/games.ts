// The games as the content pages state them, so that a page never names a game that is not there, never calls a game free that is
// Pro, and the counts are the catalogue's own.
//
// The pages are built from a SNAPSHOT of the catalogue (packages/web/content/catalogue.snapshot.json), not from the manifests
// directly. `node packages/web/content/build.ts` reads the manifests (packages/games/<id>/manifest.json), refreshes the snapshot and
// writes the pages. The tests build from the snapshot, so a builder who changes a manifest (a tagline, a round length) does not
// turn the test run red with pages he did not write; they say, in a warning, that the pages are behind. The launch check
// (BA_RELEASE=1) and `build.ts --check --strict` fail while the snapshot differs from the manifests: no page goes live behind them.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadCatalogue } from '../../catalogue/load.ts';
import { localized } from '../../../core/ui/i18n/localized.ts';
import type { Lang } from '../facts.ts';

export interface Pair { en: string; tr: string }

/** What the pages use of one game. */
export interface SnapshotGame {
  id: string;
  slug: string;
  title: Pair;
  free: boolean;
  seated: boolean;
  lowImpact: boolean;
  quiet: boolean;
  seconds: number;
  /** Two people side by side at one camera. */
  local2: boolean;
  /** A live race against a friend in a room. */
  live: boolean;
  tagline: Pair;
  about: Pair;
}

export const SNAPSHOT_FILE = join(dirname(fileURLToPath(import.meta.url)), '..', 'catalogue.snapshot.json');
const NOTE = 'Generated by node packages/web/content/build.ts from packages/games/*/manifest.json. The content pages are built from this file; do not edit it by hand.';

const pair = (v: Parameters<typeof localized>[0]): Pair => ({ en: localized(v, 'en'), tr: localized(v, 'tr') });

/** What the manifests say now, in the order of the menu. Throws when the catalogue has a problem (a game without Turkish text is one). */
export function liveGames(): SnapshotGame[] {
  const { catalogue, problems } = loadCatalogue({ fixtures: 'none', requiredLangs: ['en', 'tr'] });
  if (problems.length > 0) throw new Error(`the game catalogue has problems: ${problems.map((p) => `${p.where}: ${p.message}`).join('; ')}`);
  return [...catalogue.games].sort((a, b) => a.catalogue.order - b.catalogue.order).map((g) => ({
    id: g.id,
    slug: g.seo.slug,
    title: pair(g.title),
    free: g.free,
    seated: g.seated,
    lowImpact: g.lowImpact,
    quiet: g.silentSafe,
    seconds: g.durationSec,
    local2: g.modes.includes('local2'),
    live: g.modes.includes('duel'),
    tagline: pair(g.catalogue.tagline),
    about: pair(g.catalogue.about),
  }));
}

let cache: SnapshotGame[] | null = null;

/** The games as the pages were last built. */
export function snapshotGames(): SnapshotGame[] {
  if (cache) return cache;
  const data = JSON.parse(readFileSync(SNAPSHOT_FILE, 'utf8')) as { games?: SnapshotGame[] };
  if (!Array.isArray(data.games) || data.games.length === 0) throw new Error(`${SNAPSHOT_FILE} holds no games: run node packages/web/content/build.ts`);
  cache = data.games;
  return cache;
}

/** Does the snapshot say what the manifests say now? */
export function snapshotIsCurrent(): boolean {
  try { return JSON.stringify(liveGames()) === JSON.stringify(snapshotGames()); } catch { return false; }
}

/** Writes the snapshot from the manifests; true when the file changed. */
export function refreshSnapshot(): boolean {
  const games = liveGames();
  let before = '';
  try { before = JSON.stringify(snapshotGames()); } catch { /* none yet */ }
  if (before === JSON.stringify(games)) return false;
  writeFileSync(SNAPSHOT_FILE, `${JSON.stringify({ note: NOTE, games }, null, 1)}\n`);
  cache = games;
  return true;
}

export interface GameInfo {
  id: string;
  slug: string;
  title: string;
  free: boolean;
  seated: boolean;
  lowImpact: boolean;
  quiet: boolean;
  seconds: number;
  local2: boolean;
  live: boolean;
  tagline: string;
  about: string;
}

export function gameList(lang: Lang): GameInfo[] {
  return snapshotGames().map((g) => ({
    id: g.id, slug: g.slug, title: g.title[lang], free: g.free, seated: g.seated, lowImpact: g.lowImpact, quiet: g.quiet,
    seconds: g.seconds, local2: g.local2, live: g.live, tagline: g.tagline[lang], about: g.about[lang],
  }));
}

export interface GameCounts {
  total: number;
  free: number;
  pro: number;
  seated: number;
  quiet: number;
  local2: number;
  live: number;
  shortest: number;
  longest: number;
}

export function gameCounts(): GameCounts {
  const g = gameList('en');
  return {
    total: g.length,
    free: g.filter((x) => x.free).length,
    pro: g.filter((x) => !x.free).length,
    seated: g.filter((x) => x.seated).length,
    quiet: g.filter((x) => x.quiet).length,
    local2: g.filter((x) => x.local2).length,
    live: g.filter((x) => x.live).length,
    shortest: Math.min(...g.map((x) => x.seconds)),
    longest: Math.max(...g.map((x) => x.seconds)),
  };
}

/** "A", "A and B", "A, B and C" (Turkish: "A ve B", "A, B ve C"). */
export function listWords(items: readonly string[], lang: Lang): string {
  const and = lang === 'tr' ? 've' : 'and';
  if (items.length <= 1) return items[0] ?? '';
  return `${items.slice(0, -1).join(', ')} ${and} ${items[items.length - 1]}`;
}

/** The titles of the games that match, as a sentence list. */
export function titlesOf(filter: (g: GameInfo) => boolean, lang: Lang): string {
  return listWords(gameList(lang).filter(filter).map((g) => g.title), lang);
}

/**
 * Seconds as the pages say a round: "90 seconds", "7 minutes", and "about 5 minutes" for a round that is not a whole number of
 * minutes (Turkish: "90 saniye", "7 dakika", "yaklaşık 5 dakika").
 */
export function roundLength(seconds: number, lang: Lang): string {
  if (seconds < 120) return lang === 'tr' ? `${seconds} saniye` : `${seconds} seconds`;
  const m = Math.round(seconds / 60);
  const exact = seconds % 60 === 0;
  if (lang === 'tr') return `${exact ? '' : 'yaklaşık '}${m} dakika`;
  return `${exact ? '' : 'about '}${m} minutes`;
}
