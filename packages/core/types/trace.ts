// Trace format: recorded landmark frames, the input of every detector and calibration test.
// A trace holds landmarks only, never video. The JSON file layout is TraceFile (schema: trace.schema.json,
// example: trace.example.json); code works with the parsed Trace. Parse, serialise and replay live in core/pose.
import type { LandmarkFrameSource } from './camera.ts';
import type { Ms, Side } from './common.ts';
import type { Framing } from './body.ts';
import type { MovementEvent, MovementId } from './moves.ts';
import type { Landmark, PoseFrame, PoseService } from './pose.ts';

export const TRACE_FORMAT = 'bodyarcade-trace';
export const TRACE_VERSION = 1;

/** Where the landmarks came from. 'synthetic' traces are generated by code and never count as real-body evidence. */
export type TraceOrigin = 'recorded' | 'video' | 'synthetic';

export interface TraceMeta {
  /** Short stable name, used in test output: 'jump-3x-tall-laptop'. */
  id: string;
  origin: TraceOrigin;
  framing: Framing;
  /** e.g. 'pose_landmarker_lite float16, tasks-vision 1.1.1, GPU'. */
  model?: string;
  /** ISO date-time of the recording. */
  recordedAt?: string;
  /** Free text: camera, room, distance. Nothing that identifies a person. */
  device?: string;
  notes?: string;
  /** Opt-in tester sessions: landmarks only, with consent recorded by the tester page. */
  consent?: 'opt-in' | 'licensed' | 'own';
}

/**
 * Hand-labelled ground truth. Movement labels use the MovementEvent kinds so a detector's output can be compared
 * directly (recall, precision, delay; tech.md 4.4). 'marker' labels note scene changes ('still', 'leave', 'enter').
 */
export interface TraceLabel {
  t: Ms;
  id: MovementId | 'still' | 'leave' | 'enter';
  kind: MovementEvent['kind'] | 'marker';
  side?: Side;
  note?: string;
}

/** One frame in memory. `t` counts from the start of the trace. */
export interface TraceFrame { t: Ms; lm: Landmark[] | null; inferenceMs?: number }

export interface Trace {
  /** Nominal capture rate; frames carry their own times, which may jitter or skip. */
  fps: number;
  /** Width / height of the analysed image. */
  aspect: number;
  meta: TraceMeta;
  labels: TraceLabel[];
  frames: TraceFrame[];
}

/** The JSON file. Landmarks are flat: [x, y, z, visibility] x 33 = 132 numbers in MediaPipe order, or null. */
export interface TraceFile {
  format: typeof TRACE_FORMAT;
  version: typeof TRACE_VERSION;
  fps: number;
  aspect: number;
  meta: TraceMeta;
  labels?: TraceLabel[];
  frames: { t: Ms; lm: number[] | null; ms?: number }[];
}

export interface TraceSourceOptions {
  /** Resample to this rate, as a slow device would deliver it (B7: 4, 10, 30 Hz). Default: the trace's own times. */
  hz?: number;
  loop?: boolean;
  /** Playback speed factor; 1 is real time. */
  speed?: number;
}

/** Plays a trace through the same path a camera uses (PoseService.attach). */
export type TraceSourceFn = (t: Trace, o?: TraceSourceOptions) => LandmarkFrameSource;

/** Pure, for Node tests: the frames a device running at `hz` would see, as PoseFrames starting at `t0`. */
export type TraceFramesFn = (t: Trace, o?: { hz?: number; t0?: Ms; source?: PoseFrame['source'] }) => PoseFrame[];

export interface TraceRecording {
  readonly frames: number;
  /** Stops recording and returns the trace (labels empty unless added). */
  stop(): Trace;
}

/** Dev page tool: records what the pose service delivers. Landmarks only. */
export type RecordTraceFn = (pose: PoseService, meta: Omit<TraceMeta, 'origin'> & { origin?: TraceOrigin }) => TraceRecording;

/** Parses and validates untrusted JSON; throws TraceFormatError with the failing path. */
export type ParseTraceFn = (json: unknown) => Trace;
export type SerializeTraceFn = (t: Trace, o?: { decimals?: number }) => TraceFile;
